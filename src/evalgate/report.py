"""The evaluation report: the baseline, the judge's calibration, and the gate's verdict on each variant."""

from __future__ import annotations

from typing import Any

from evalgate.gate import Decision, Policy

KEYS = [
    "pass_rate",
    "critical_pass_rate",
    "faithfulness",
    "citation_recall",
    "citation_precision",
    "abstention_accuracy",
    "refusal_accuracy",
    "tool_accuracy",
]


def markdown(base: dict[str, Any], cal: dict[str, Any], rows: list[tuple[str, dict[str, Any], Decision]], policy: Policy) -> str:
    m = base["metrics"]
    n = len(base["cases"])
    lines = [
        "# Evaluation report",
        "",
        f"Generated by `evg variants`. Golden set `{base['meta']['golden_digest']}`: {n} cases. Judge "
        f"`{cal['judge']}`, threshold {cal['threshold']:.2f}.",
        "",
        "## The gate on five candidate changes",
        "",
        "Each variant is the reference agent with one setting changed, the kind of change a pull request makes. "
        "Each is run over the golden set, graded, judged and gated against the baseline.",
        "",
        "| Variant | Change | Pass rate | Critical | Faithfulness | Citation recall | Abstention | Verdict | First reason |",
        "|---|---|---|---|---|---|---|---|---|",
        f"| baseline | the agent on main | {m['pass_rate']:.3f} | {m['critical_pass_rate']:.3f} | {m['faithfulness']:.3f} | {m['citation_recall']:.3f} | "
        f"{m['abstention_accuracy']:.3f} | | |",
    ]
    for name, cand, d in rows:
        c = cand["metrics"]
        change = ", ".join(f"{k}={v}" for k, v in cand["meta"]["config"].items() if k != "name" and base["meta"]["config"].get(k) != v)
        verdict = "**blocked**" if d.blocked else "passed"
        lines.append(
            f"| {name} | {change} | {c['pass_rate']:.3f} | {c['critical_pass_rate']:.3f} | {c['faithfulness']:.3f} | "
            f"{c['citation_recall']:.3f} | {c['abstention_accuracy']:.3f} | {verdict} | {d.reasons[0] if d.reasons else '-'} |"
        )
    lines += ["", "## What the gate saw", ""]
    for name, _, d in rows:
        lines.append(f"### {name}")
        lines.append("")
        lines += [f"- {r}" for r in d.reasons] or ["- No rule triggered."]
        if d.regressed:
            lines.append(f"- Regressed: {', '.join(r['id'] for r in d.regressed)}")
        if d.fixed:
            lines.append(f"- Fixed: {', '.join(d.fixed)}")
        lo, hi = d.pass_rate_ci
        lines += [f"- Pass-rate change, 95% interval {lo:+.3f} to {hi:+.3f}; McNemar p = {d.mcnemar_p:.3f}", ""]
    lines += [
        "## Baseline by category",
        "",
        "| Category | Pass rate |",
        "|---|---|",
    ]
    lines += [f"| {k.split(':', 1)[1]} | {v:.3f} |" for k, v in m.items() if k.startswith("pass_rate:")]
    failing = [c for c in base["cases"] if not c["passed"]]
    lines += [
        "",
        f"The baseline fails {len(failing)} of {n} cases; the gate holds candidates to not doing worse, and these are the backlog:",
        "",
    ]
    for c in failing:
        bad = [f"{g['name']} ({g['detail']})" for g in c["grades"] if not g["passed"]]
        if c.get("faithful") is False:
            bad.append("judge: unsupported: " + "; ".join(c["unsupported"]))
        lines.append(f"- `{c['id']}`: {'; '.join(bad)}")
    det = ", ".join(f"{k} {v:.0%}" for k, v in cal["detection"].items())
    lines += [
        "",
        "## The judge",
        "",
        f"Calibrated on {cal['statements']} statements with known labels: kappa {cal['kappa']:.3f}, accuracy {cal['accuracy']:.3f} at "
        f"threshold {cal['threshold']:.2f}. Judged correctly, by kind: {det}. The gate refuses to use a judge below kappa "
        f"{policy.min_judge_kappa}.",
    ]
    return "\n".join(lines) + "\n"
